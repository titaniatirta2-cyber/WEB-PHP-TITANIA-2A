<?php
// OPERATOR INCREMENT & DECREMENT
//Operator INCREMENT digunakan untuk menambah nilai variabel sebesar 1, sedangkan operator DECREMENT digunakan untuk mengurangi nilai variabel sebesar 1.
 
$score = 0;
 
$score++;
$score++;
$score++; 
 
//nilanya bertambah 3
echo '<br> nilai $score sekarang='.$score; //3
 
$score--;
$score--;
 
//nilainya berkurang 2
echo '<br> nilai $score sekarang='.$score; //1
 
?>